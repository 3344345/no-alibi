def _choice(id, label, result, next, *, marks=(), requires=(), cites=(), tone=None):
    choice = dict(id=id, label=label, result=result, next=next)
    for key, values in (("marks", marks), ("requires", requires), ("cites", cites)):
        if values:
            choice[key] = list(values)
    if tone:
        choice["tone"] = tone
    return choice


def _scene(id, title, body, choices, *, exhibits=()):
    scene = dict(id=id, title=title, body=body, choices=choices)
    if exhibits:
        scene["exhibits"] = [
            dict(id=key, title=name, detail=detail) for key, name, detail in exhibits
        ]
    return scene


