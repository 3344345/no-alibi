def room(key, title, body, choices, *echoes):
    item = dict(id="xian_" + key, title=title, body=body, choices=choices)
    if echoes:
        item["echoes"] = [{"mark": m, "body": b} for m, b in echoes]
    return item


def turn(key, label, result, dest, mark=None, need=()):
    return dict(id=key, label=label, result=result, next=dest if dest == "END" else "xian_" + dest,
                marks=[mark] if mark else [], requires=list(need))


