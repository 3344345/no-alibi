def action(key, label, result, dest, mark=None, *, requires=None, cites=(), tone=None):
    return {
        "id": key, "label": label, "result": result,
        "next": "END" if dest == "END" else "night_" + dest,
        "marks": [mark] if mark else [], "requires": list(requires or ()),
        "cites": list(cites), "tone": tone,
    }


def scene(key, title, body, *choices, echoes=(), exhibits=()):
    return {
        "id": "night_" + key, "title": title, "body": body, "choices": list(choices),
        "echoes": [{"mark": mark, "body": detail} for mark, detail in echoes],
        "exhibits": [{"id": i, "title": t, "detail": d} for i, t, d in exhibits],
    }


