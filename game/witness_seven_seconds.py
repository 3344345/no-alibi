def turn(key, label, result, destination, *, mark=None, needs=()):
    return choice(key, label, result, "END" if destination == "END" else "reel_" + destination,
                  marks=(mark,) if mark else (), requires=needs)


def scene(key, title, text, *options, echoes=()):
    return dict(id="reel_" + key, role="邓小平 · 电台来客", title=title, body=text, choices=list(options),
                echoes=[echo(mark, text) for mark, text in echoes])


