def attach_desks(chapters):
    chapters = deepcopy(chapters)
    for chapter in chapters:
        title, question, materials, verdicts = DESKS[chapter["id"]]
        opening = chapter["scenes"][0]
        # Returning offers every original opening route, including companion arcs.
        back = {**deepcopy(opening), "id": "desk_return"}
        desk = {
            "id": "desk_inspect", "title": title, "body": question,
            "exhibits": [
                {"id": key, "title": name, "detail": detail}
                for key, (name, detail) in zip("abc", materials, strict=True)
            ],
            "choices": [
                {"id": f"weigh_{n}", "label": label, "result": result,
                 "marks": [mark], "next": "desk_return", "cites": list(pair)}
                for n, (pair, label, result, mark) in enumerate(verdicts)
            ],
        }
        opening["choices"].append({
            "id": "open_desk", "label": "案头核对 · " + title,
            "result": "三份材料已经摊开。", "next": "desk_inspect",
        })
        chapter["scenes"].extend((desk, back))
    return chapters
