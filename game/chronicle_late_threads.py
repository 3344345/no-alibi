def choice(key, label, result, following, *, marks=(), requires=(), tone=None):
    entry = {"id": key, "label": label, "result": result, "next": following}
    if marks:
        entry["marks"] = list(marks)
    if requires:
        entry["requires"] = list(requires)
    if tone:
        entry["tone"] = tone
    return entry


def scene(key, title, body, *choices):
    return {"id": key, "title": title, "body": body, "choices": list(choices)}


