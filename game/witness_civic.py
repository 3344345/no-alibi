def scene(key, title, body, *choices):
    return {"id": key, "title": title, "body": body, "choices": list(choices)}


def choose(key, label, result, following, *, gain=None, need=None, tone=None):
    row = {"id": key, "label": label, "result": result, "next": following}
    if gain:
        row["marks"] = [gain]
    if need:
        row["requires"] = [need]
    if tone:
        row["tone"] = tone
    return row


def source(name, url):
    return {"name": name, "url": url}


