def option(key, label, result, following, *, mark=None, needs=None, cites=()):
    item = {"id": key, "label": label, "result": result, "next": following}
    if mark is not None:
        item["marks"] = [mark]
    if needs is not None:
        item["requires"] = [needs]
    if cites:
        item["cites"] = list(cites)
    return item


def scene(key, title, body, *choices, echoes=(), exhibits=()):
    item = {"id": key, "title": title, "body": body, "choices": list(choices)}
    if exhibits:
        item["exhibits"] = [dict(id=key, title=title, detail=detail) for key, title, detail in exhibits]
    if echoes:
        item["echoes"] = [{"mark": mark, "body": text} for mark, text in echoes]
    return item


