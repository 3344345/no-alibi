def option(key, label, result, following, *, mark=None, needs=None):
    item = {"id": key, "label": label, "result": result, "next": following}
    if mark is not None:
        item["marks"] = [mark]
    if needs is not None:
        item["requires"] = [needs]
    return item


def scene(key, title, body, *choices):
    return {"id": key, "title": title, "body": body, "choices": list(choices)}


